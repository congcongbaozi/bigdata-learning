    public static int[] twoSumHash(int[] nums, int target){

        //方法2：时间 O(n)，空间 O(n)，哈希表，先用大白话讲整体思路。你可以把 map 想成一张两列的登记表：左列记数值，右列记这个数值出现在哪个下标。程序从左往右走数组，每走到一个数，它就先算"还差多少能凑够目标"，然后翻登记表看这个差额有没有被记过。差额没被记过，程序就把当前数值登记进去；差额被记过，程序就直接报出两个下标。这么做的代价是多占一份内存，换来的是每个位置只翻一次表，不用两两去试。
        Map<Integer, Integer> map = new HashMap<>();//这一行造出那张登记表，变量名叫 map。Map 是 Java 规定的一种"键值对"接口，HashMap 是它的一个具体实现；尖括号里的两个 Integer 规定键和值都只能放整数。等号右边的 new HashMap<>() 才真正创建对象，等号左边只是说明这个对象的类型。在这段程序里，键放数组里的数值，值放该数值的下标。
        for(int i = 0; i < nums.length; i++)//这一行开启一轮从左往右的循环。变量 i 从 0 出发，每轮加 1，只要 i 还小于 nums.length（数组的元素个数），循环就继续。Java 的下标从 0 算起，所以 i 依次代表第 0 个、第 1 个、第 2 个位置。{ 表示循环体开始。
        {
            int need = target - nums[i];//这一行计算"还差多少才凑得够目标"。nums[i] 是当前位置的数值，程序用 target 减掉它，把结果存进整数变量 need。need 就是程序要找的配对数值。
            if(map.containsKey(need))
            {
                return new int[]{map.get(need), i};//这一行在配对成功时交出答案并立刻结束方法。map.get(need) 取出当时记下的那个下标，i 是当前下标，new int[]{...} 现场拼出一个长度为 2 的数组。return 一旦执行，后面的语句都不再运行。

            }//这一行闭合 if 的花括号，"查到了就返回"这个分支到此为止。
            map.put(nums[i], i);//这一行把当前数值和当前下标写进登记表，留给后面的位置来查。put 的第一个参数是键，第二个参数是值。它排在 if 后面，因此只有"没查到"的时候才会执行，这个顺序让程序不可能拿当前元素跟自己配对。// 之后是给人看的注释，编译器会忽略它。

        }//这一行闭合 for 的花括号，程序回到for循环去判断要不要开始下一轮。
        return new int[]{};//这一行在整轮循环都没找到答案时交回一个空数组。题设声明每种输入都有唯一答案，所以合法输入下它不会被执行；但方法声明了要返回 int[]，Java 要求所有可能的执行路径都有返回值，这一行满足了该要求。
    }
//三个小白容易卡住的点
//你可以把 nums = [2,7,11,15] 想成一排带编号的格子，编号从 0 开始，所以 nums[0] 是 2，nums[1] 是 7。你可以把"键 → 值"想成查字典：map.get(2) 问的是"数值 2 的下标是多少"，而不是"下标 2 的数值是多少"。笔记把这一解的耗时记作 O(n)、额外内存记作 O(n) ("001-two-sum.md", 第 39 行)，原因是程序只把数组走了一遍，而登记表最多收下全部元素。
//
//笔记还解释了为什么不能先一次性塞满登记表再查 ("001-two-sum.md", 第 42–47 行)。我按原意重述一遍：若先全塞进去，nums = [3,3]、target = 6 时后写的下标会盖掉先写的下标，程序随后会交回 [1,1]，也就是把同一个位置用了两遍，这违反题目限制。第 34 行排在判断之后，正好挡住了这类错误



